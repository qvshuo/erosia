SOLVER_TIMEOUT_SECONDS = 45


@dataclass
class Page:
    url: str
    status: int
    body: bytes
    fetcher: str = "scrapling"

    @cached_property
    def text(self) -> str:
        # Browser output is UTF-8; legacy Japanese HTML declares EUC-JP or Shift_JIS.
        charset = re.search(rb'charset\s*=\s*["\']?([\w-]+)', self.body[:8192], re.I)
        encoding = (
            charset[1].decode("ascii") if charset and self.fetcher == "scrapling" else "utf-8"
        )
        try:
            return self.body.decode(encoding, errors="replace")
        except LookupError:
            return self.body.decode("utf-8", errors="replace")

    @cached_property
    def _selector(self) -> Selector:
        return Selector(self.text, url=self.url, adaptive=False)

    def selector(self) -> Selector:
        return self._selector

    def json(self) -> JsonValue:
        try:
            return json.loads(self.body)
        except (ValueError, UnicodeDecodeError) as exc:
            raise FetchError(Status.PARSE_ERROR, "invalid JSON response", self) from exc



class FetchError(Exception):
    def __init__(self, status: Status, message: str, page: Page | None = None) -> None:
        super().__init__(message)
        self.status = status
        self.page = page


class Session(Protocol):
    async def get(self, url: str, **kwargs: Any) -> Response: ...
    async def post(self, url: str, **kwargs: Any) -> Response: ...


class Client(Protocol):
    async def get(
        self,
        source: SourceId,
        url: str,
        *,
        headers: dict[str, str] | None = None,
        cookies: dict[str, str] | None = None,
        rendered: bool = False,
        wait_seconds: int = 0,
    ) -> Page: ...
    async def post_json(
        self,
        source: SourceId,
        url: str,
        payload: JsonValue,
        *,
        headers: dict[str, str] | None = None,
    ) -> Page: ...


def response_issue(page: Page) -> tuple[Status, str] | None:
    text = page.text.lower()
    path = urlparse(page.url).path.lower()
    if "error 1005" in text or ("access denied" in text and "autonomous system" in text):
        return Status.IP_BLOCKED, "source denied the exit IP/ASN"
    if "not-available-in-your-region" in path or "not available in your region" in text:
        return Status.REGION_BLOCKED, "source is unavailable from this exit region"
    if "/login" in path or "log in  fc2" in text[:1000] or "此內容需要登入" in text:
        return Status.LOGIN_REQUIRED, "source requires an authenticated session"
    if text.lstrip("\ufeff \t\r\n").startswith("<"):
        title = page.selector().css("title::text").get("").strip().lower()
        if re.search(r"login|sign in|登录|登入", title) and page.selector().css('form input[type="password"]'):
            return Status.LOGIN_REQUIRED, "source requires an authenticated session"
        if title.startswith(("checking your browser", "security verification", "安全验证", "安全驗證")):
            return Status.BLOCKED, "source verification page remains"
    if "generated by cloudfront" in text and "request blocked" in text:
        return Status.BLOCKED, "CloudFront rejected the request"
    if "/doc/driver-verify" in path:
        return Status.BLOCKED, "JavBus verification gate"
    if page.status == 404:
        return Status.NOT_FOUND, "source returned HTTP 404"
    if page.status >= 400:
        return Status.BLOCKED if page.status in (
            401,
            403,
        ) else Status.NETWORK_ERROR, f"HTTP {page.status}"
    return None


def is_cloudflare(page: Page) -> bool:
    text = page.text.lower()
    # Successful pages also embed Cloudflare's challenge-platform JS. A script URL
    # alone is not evidence that the requested document is a challenge page.
    title = page.selector().css("title::text").get("").strip().lower() if "<" in text[:200] else ""
    return (
        title.startswith(("just a moment", "attention required"))
        or ("cloudflare" in text and ("autonomous system" in text or "access denied" in title))
        or (
            "cf-chl-" in text
            and ("enable javascript and cookies" in text or "verify you are human" in text)
        )
    )


class WebClient:
    """Pooled Scrapling sessions; solver cookies never migrate between exits."""

    _budgets = WeakKeyDictionary()

    def __init__(self, settings: Settings, *, runtime=None) -> None:
        self.settings = settings
        self.runtime = runtime
        self.cooldowns = runtime.cooldowns() if runtime is not None else {}
        self._stack = AsyncExitStack()
        self._sessions: dict[tuple[SourceId, str], Session] = {}
        self._session_lock = asyncio.Lock()
        self._source_locks: dict[SourceId, asyncio.Lock] = {}
        self._host_locks: dict[str, asyncio.Lock] = {}
        self._last_request: dict[str, float] = {}
        self._metadata_last: dict[str, float] = {}
        self._work_scope = ContextVar("source_work", default=None)
        self._paced_work = {}
        self._limit = asyncio.Semaphore(8)
        self._solver_limit = asyncio.Semaphore(1)
        self._solver_sessions: dict[tuple[SourceId, str], str] = {}
        self._solver_lock = asyncio.Lock()
        self._control: httpx.AsyncClient | None = None

    def share_limits(self):
        # Task workers and image previews share the same host pacing budget.
        loop = asyncio.get_running_loop()
        if loop not in self._budgets:
            self._budgets[loop] = ({}, {}, {}, asyncio.Semaphore(8), asyncio.Semaphore(1))
        self._source_locks, self._host_locks, self._last_request, self._limit, self._solver_limit = self._budgets[loop]

    def _save_cooldown(self, source, row):
        self.cooldowns[str(source)] = row
        if self.runtime is not None:
            self.runtime.save_cooldown(source, row)

    def cooldown_key(self, source, url=None):
        if source != SourceId.DMM:
            return source
        settings = self.settings.sites.get(source)
        origin = url or (settings.base_url if settings and settings.base_url else "https://api.video.dmm.co.jp")
        # DMM's API and web search have independently enforced access restrictions.
        return f"dmm:{urlparse(origin).hostname}"

    def cool_down(self, source, seconds, reason):
        row = dict(self.cooldowns.get(str(source), {}))
        row.update(cooldown_until=max(row.get("cooldown_until", 0), time.time() + seconds), cooldown_reason=reason)
        self._save_cooldown(source, row)

    def record_outcome(self, source, status):
        if status in (Status.IP_BLOCKED, Status.REGION_BLOCKED, Status.BLOCKED):
            self.cool_down(source, 900, str(status))
        elif status == Status.LOGIN_REQUIRED:
            self.cool_down(source, 300, str(status))

    def check_cooldown(self, source):
        row = self.cooldowns.get(str(source), {})
        remaining = row.get("cooldown_until", 0) - time.time()
        if remaining > 0:
            reason = {"region_blocked": "当前出口受地区限制", "ip_blocked": "当前出口 IP 被拒绝", "blocked": "来源拒绝访问", "login_required": "来源要求登录", "rate_limited": "来源限制请求频率"}.get(row.get("cooldown_reason"), "来源暂停请求")
            if source == SourceId.FC2 and row.get("cooldown_reason") == "login_required":
                reason = "FC2 要求登录"
            wait = f"{ceil(remaining / 60)} 分钟" if remaining >= 60 else f"{ceil(remaining)} 秒"
            raise FetchError(Status.COOLDOWN, f"{reason}，暂停重复请求，剩余 {wait}")

    async def __aenter__(self) -> WebClient:
        await self._stack.__aenter__()
        self._control = await self._stack.enter_async_context(
            httpx.AsyncClient(
                timeout=SOLVER_TIMEOUT_SECONDS + 15,
                trust_env=False,
            )
        )
        return self

    async def __aexit__(self, *exc: Any) -> None:
        try:
            if self._control and self.settings.flaresolverr_url:
                for session in self._solver_sessions.values():
                    try:
                        await self._control.post(
                            self.settings.flaresolverr_url,
                            json={"cmd": "sessions.destroy", "session": session},
                            timeout=10,
                        )
                    except httpx.HTTPError:
                        pass
        finally:
            await self._stack.__aexit__(*exc)
            self._sessions.clear()
            self._solver_sessions.clear()

    async def _session(self, source: SourceId, url: str) -> Session:
        key = source, urlparse(url).netloc
        async with self._session_lock:
            if key not in self._sessions:
                self._sessions[key] = await self._stack.enter_async_context(
                    FetcherSession(
                        impersonate="chrome",
                        timeout=self.settings.timeout_seconds,
                        retries=0,
                        selector_config={"adaptive": False},
                    )
                )
            return self._sessions[key]

    @contextmanager
    def source_work(self):
        token = self._work_scope.set(object())
        try:
            yield
        finally:
            self._work_scope.reset(token)

    def source_wait_seconds(self, source: SourceId) -> int:
        previous = self._metadata_last.get(f"source:{source}")
        interval = self.settings.source_interval(source)
        remaining = interval - (time.monotonic() - previous) if previous is not None else 0
        cooldown = self.cooldowns.get(str(self.cooldown_key(source)), {}).get("cooldown_until", 0) - time.time()
        return max(0, ceil(max(remaining, cooldown)))

    async def _throttle(self, source: SourceId, host: str, binary: bool = False) -> None:
        interval = 1 if binary else self.settings.source_interval(source)
        key = f"image:{host}" if binary else f"source:{source}"
        history = self._last_request if binary else self._metadata_last
        previous = history.get(key)
        delay = interval - (time.monotonic() - previous) if previous is not None else 0
        if delay > 0:
            report_progress("wait", source=source, message=f"{'图片间隔' if binary else '冷却'} {ceil(delay)} 秒")
            await asyncio.sleep(delay)
        history[key] = time.monotonic()

    async def get(
        self,
        source: SourceId,
        url: str,
        *,
        headers: dict[str, str] | None = None,
        cookies: dict[str, str] | None = None,
        rendered: bool = False,
        wait_seconds: int = 0,
    ) -> Page:
        return await self._request(
            source, url, "GET", headers=headers, cookies=cookies, rendered=rendered, wait_seconds=wait_seconds
        )

    async def post_json(
        self,
        source: SourceId,
        url: str,
        payload: JsonValue,
        *,
        headers: dict[str, str] | None = None,
    ) -> Page:
        return await self._request(source, url, "POST", payload=payload, headers=headers)

    async def image_bytes(self, source: SourceId, url: str, referer: str) -> bytes:
        page = await self._request(source, url, "GET", headers={"Referer": referer}, binary=True)
        return page.body

    async def _request(self, source: SourceId, url: str, method: str, **kwargs: Any) -> Page:
        try:
            return await self._fetch(source, url, method, **kwargs)
        except FetchError as exc:
            if not kwargs.get("binary", False):
                self.record_outcome(self.cooldown_key(source, url), exc.status)
            raise

    async def _fetch(
        self,
        source: SourceId,
        url: str,
        method: str,
        *,
        payload: JsonValue = None,
        headers: dict[str, str] | None = None,
        cookies: dict[str, str] | None = None,
        rendered: bool = False,
        wait_seconds: int = 0,
        binary: bool = False,
    ) -> Page:
        self.share_limits()
        parsed = urlparse(url)
        if parsed.scheme != "https" or not parsed.hostname or parsed.username or parsed.password:
            raise FetchError(Status.UNSUPPORTED, "site URLs must use HTTPS")
        cooldown_key = self.cooldown_key(source, url)
        if not binary:
            self.check_cooldown(cooldown_key)
        host_lock = self._host_locks.setdefault(parsed.hostname, asyncio.Lock())
        settings = self.settings.sites.get(source)
        # Artwork CDNs must not receive the source site's account cookies.
        cookie_host = (
            urlparse(settings.base_url or "https://javdb.com").hostname
            if settings and source == SourceId.JAVDB
            else None
        )
        configured = settings.cookie_values() if settings and parsed.hostname == cookie_host else {}
        combined_cookies = {} if binary else {**(cookies or {}), **configured}
        source_lock = self._source_locks.setdefault(source, asyncio.Lock())
        async with AsyncExitStack() as locks:
            if not binary:
                await locks.enter_async_context(source_lock)
                self.check_cooldown(cooldown_key)
                scope = self._work_scope.get()
                if scope is None or self._paced_work.get(source) is not scope:
                    await self._throttle(source, parsed.netloc)
                    self._paced_work[source] = scope
            await locks.enter_async_context(host_lock)
            await locks.enter_async_context(self._limit)
            if (
                method == "GET"
                and not binary
                and (rendered or (source, parsed.netloc) in self._solver_sessions)
            ):
                return await self._render(source, url, combined_cookies, wait_seconds=wait_seconds)
            session = await self._session(source, url)
            for attempt in range(self.settings.retries + 1):
                if binary:
                    await self._throttle(source, parsed.netloc, True)
                report_progress(
                    "request",
                    source=source,
                    message=f"{'图片' if binary else method} {parsed.netloc}{parsed.path}",
                )
                try:
                    kwargs = {"headers": headers or {}, "cookies": combined_cookies, "timeout": self.settings.timeout_seconds}
                    response = (
                        await session.get(url, **kwargs)
                        if method == "GET"
                        else await session.post(url, json=payload, **kwargs)
                    )
                    page = Page(str(response.url), response.status, response.body)
                    report_progress("response", source=source, message=f"HTTP {page.status}")
                except Exception as exc:  # Scrapling wraps several curl transport exception types.
                    if attempt < self.settings.retries:
                        report_progress("retry", source=source, message="网络请求失败，准备重试")
                        await asyncio.sleep(self.settings.retry_delay_seconds)
                        continue
                    raise FetchError(
                        Status.NETWORK_ERROR, f"transport failed ({type(exc).__name__})"
                    ) from exc
                if is_cloudflare(page):
                    if binary:
                        raise FetchError(
                            Status.BLOCKED,
                            "image CDN challenged the request; solver API cannot return binary artwork",
                            page,
                        )
                    if method == "GET":
                        return await self._render(source, url, combined_cookies, wait_seconds=wait_seconds)
                    raise FetchError(
                        Status.BLOCKED,
                        "CF blocked a JSON endpoint; browser form POST cannot replace JSON",
                        page,
                    )
                if page.status == 429:
                    retry_after = response.headers.get("retry-after", "")
                    try:
                        seconds = float(retry_after) if retry_after.isdigit() else parsedate_to_datetime(retry_after).timestamp() - time.time()
                    except (ValueError, TypeError, OverflowError):
                        seconds = 900
                    if not binary:
                        self.cool_down(cooldown_key, max(1, min(seconds, 86400)), "rate_limited")
                    raise FetchError(Status.RATE_LIMITED, "来源限流，请等待冷却", page)
                if page.status >= 500:
                    if attempt < self.settings.retries:
                        retry_after = response.headers.get("retry-after", "")
                        seconds = (
                            min(int(retry_after), 30)
                            if retry_after.isdigit()
                            else self.settings.retry_delay_seconds
                        )
                        delay = 1 if seconds <= 1 else ((seconds + 4) // 5) * 5
                        await asyncio.sleep(delay)
                        continue
                if binary:
                    from .images import placeholder_url
                    if placeholder_url(source, page.url):
                        raise FetchError(Status.NOT_FOUND, "来源返回占位图", page)
                if issue := response_issue(page):
                    raise FetchError(*issue, page)
                return page
        raise AssertionError("unreachable")

    async def _solver_call(self, data: dict[str, JsonValue]) -> dict[str, JsonValue]:
        if not self._control or not self.settings.flaresolverr_url:
            raise FetchError(Status.BLOCKED, "FlareSolverr is disabled or client is not open")
        try:
            response = await self._control.post(self.settings.flaresolverr_url, json=data)
            payload = response.json()
        except (httpx.HTTPError, ValueError) as exc:
            raise FetchError(
                Status.NETWORK_ERROR, f"FlareSolverr unavailable ({type(exc).__name__})"
            ) from exc
        if not isinstance(payload, dict):
            raise FetchError(Status.PARSE_ERROR, "invalid FlareSolverr response")
        if payload.get("status") != "ok":
            message = str(payload.get("message", "FlareSolverr failed"))
            status = Status.IP_BLOCKED if "banned" in message.lower() else Status.BLOCKED
            raise FetchError(status, message)
        return payload

    async def _render(self, source: SourceId, url: str, cookies: dict[str, str], *, wait_seconds: int = 0) -> Page:
        report_progress("challenge", source=source)
        key = (source, urlparse(url).netloc)
        async with self._solver_limit:
            async with self._solver_lock:
                if key not in self._solver_sessions:
                    session = "erosia-" + uuid.uuid4().hex
                    command: dict[str, JsonValue] = {"cmd": "sessions.create", "session": session}
                    await self._solver_call(command)
                    self._solver_sessions[key] = session
            payload = await self._solver_call(
                {
                    "cmd": "request.get",
                    "url": url,
                    "session": self._solver_sessions[key],
                    "maxTimeout": SOLVER_TIMEOUT_SECONDS * 1000,
                    "waitInSeconds": wait_seconds,
                    # Browser-copied CF cookies belong to its original exit/UA.
                    # Forward login cookies while keeping the solver's own CF state.
                    "cookies": [
                        {"name": name, "value": value}
                        for name, value in cookies.items()
                        if name not in ("cf_clearance", "__cf_bm")
                    ],
                }
            )
            solution = payload.get("solution")
            if not isinstance(solution, dict) or not isinstance(solution.get("response"), str):
                raise FetchError(Status.PARSE_ERROR, "FlareSolverr returned no document")
            page = Page(
                str(solution.get("url", url)),
                int(solution.get("status", 200)),
                solution["response"].encode(),
                "flaresolverr",
            )
            if is_cloudflare(page):
                raise FetchError(Status.BLOCKED, "CF challenge remains after solver", page)
            if issue := response_issue(page):
                raise FetchError(*issue, page)
            return page
